import { createHash, randomUUID } from 'node:crypto'
import { lstat, open, readFile, rename, rm, stat, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import type { Topic } from './types.ts'

export interface ReportInfo {
  path: 'report.md' | 'design.md'
  revision: string
  updated: string
  status: 'current' | 'stale' | 'unknown'
  generation?: number
  throughRound?: number
}

export interface ReportDraft {
  markdown: string
  generation: number
  throughRound: number
  /** Empty string means the caller observed no report; otherwise SHA-256. */
  expectedRevision: string
}

export async function assertReportFiles(dir: string): Promise<void> {
  for (const name of ['report.md', 'design.md']) {
    const file = await lstat(join(dir, name)).catch(error => {
      if ((error as NodeJS.ErrnoException).code === 'ENOENT') return undefined
      throw error
    })
    if (file !== undefined && (!file.isFile() || file.isSymbolicLink())) throw new Error('report must be a regular file, not a link')
  }
}

/** The caller supplies a verified topic directory, never a model-supplied path. */
export async function writeReport(dir: string, loadTopic: () => Promise<Topic>, draft: ReportDraft): Promise<ReportInfo> {
  if (typeof draft.markdown !== 'string' || draft.markdown.trim() === '' || Buffer.byteLength(draft.markdown) > 256 * 1024) {
    throw new Error('report markdown must contain 1–262144 UTF-8 bytes')
  }
  if (draft.markdown.includes('dsh-pro-report:')) throw new Error('report coverage is generated by the plugin; omit the provenance header')
  if (typeof draft.expectedRevision !== 'string' || !/^(?:[a-f0-9]{64})?$/.test(draft.expectedRevision)) throw new Error('expected_revision must be the current report revision or an empty string')
  const lockPath = join(dir, '.report.lock')
  const lock = await open(lockPath, 'wx').catch(error => {
    if ((error as NodeJS.ErrnoException).code === 'EEXIST') throw new Error('report is being written; retry after the current writer finishes')
    throw error
  })
  const temp = join(dir, `.report-${randomUUID()}.tmp`)
  try {
    await assertReportFiles(dir)
    const topic = await loadTopic()
    const last = topic.rounds.at(-1)
    if (!Number.isInteger(draft.generation) || !Number.isInteger(draft.throughRound)
      || draft.generation !== (topic.generations?.at(-1)?.n ?? 1)
      || last?.n !== draft.throughRound || last.answeredAt === undefined
      || (last.generation ?? 1) !== draft.generation
      || (topic.runThrough ?? last.n) > last.n
      || ['queued', 'uploading', 'submitted', 'waiting', 'answered', 'adjudicating'].includes(topic.status)) {
      throw new Error('report coverage must match the latest answered round of a stopped topic; read status and evidence again')
    }
    const before = await readReportInfo(dir, topic)
    if ((before?.revision ?? '') !== draft.expectedRevision) throw new Error('report revision changed; read_report before updating')
    const path = topic.type === 'design' ? 'design.md' : 'report.md'
    const header = `<!-- dsh-pro-report: ${JSON.stringify({ generation: draft.generation, throughRound: draft.throughRound })} -->`
    await writeFile(temp, `${header}\n${draft.markdown.trim()}\n`, { encoding: 'utf8', flag: 'wx' })
    // Refuse a follow-up/other writer that started while this draft was prepared.
    const latest = await loadTopic()
    if (JSON.stringify(latest) !== JSON.stringify(topic)) throw new Error('topic changed; read status and evidence again')
    await assertReportFiles(dir)
    if (((await readReportInfo(dir, latest))?.revision ?? '') !== draft.expectedRevision) throw new Error('report revision changed; read_report before updating')
    await rename(temp, join(dir, path))
    return (await readReportInfo(dir, latest))!
  } finally {
    await rm(temp, { force: true })
    await lock.close()
    await rm(lockPath, { force: true })
  }
}

/** Provenance is supplied by the report author, never inferred from file age. */
export async function readReportInfo(dir: string, topic: Topic): Promise<ReportInfo | null> {
  let path: ReportInfo['path'] = topic.type === 'design' ? 'design.md' : 'report.md'
  let text: string
  let updated: string
  try {
    try {
      text = await readFile(join(dir, path), 'utf8')
    } catch (error) {
      if (path !== 'design.md' || (error as NodeJS.ErrnoException).code !== 'ENOENT') throw error
      // Preserve reports written by older hosts using the shared report name.
      path = 'report.md'
      text = await readFile(join(dir, path), 'utf8')
    }
    updated = (await stat(join(dir, path))).mtime.toISOString()
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return null
    throw error
  }
  const info: ReportInfo = {
    path, revision: createHash('sha256').update(text).digest('hex'), updated, status: 'unknown',
  }
  const header = /^\s*<!--\s*dsh-pro-report:\s*(\{[^\r\n]*\})\s*-->/.exec(text)
  if (header === null) return info
  try {
    const meta = JSON.parse(header[1] as string) as { generation: number; throughRound: number }
    const round = topic.rounds.find(item => item.n === meta.throughRound)
    if (!Number.isInteger(meta.generation) || !Number.isInteger(meta.throughRound)
      || round?.answeredAt === undefined || (round.generation ?? 1) !== meta.generation) return info
    info.generation = meta.generation
    info.throughRound = meta.throughRound
    const last = topic.rounds.at(-1)
    info.status = meta.generation === (topic.generations?.at(-1)?.n ?? 1)
      && last?.n === meta.throughRound && (topic.runThrough ?? last.n) <= last.n
      && !['queued', 'uploading', 'submitted', 'waiting', 'answered', 'adjudicating'].includes(topic.status)
      && updated >= round.answeredAt ? 'current' : 'stale'
  } catch { /* A legacy/malformed header has no trustworthy coverage. */ }
  return info
}
