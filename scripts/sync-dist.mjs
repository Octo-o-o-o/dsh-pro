// Generate the two public distribution repos from the monorepo.
// The monorepo stays the source of truth; the dist repos hold committed lib/.
//
//   npm run build
//   node scripts/sync-dist.mjs
//
// Then review and commit each repo under C:\WorkSpace\dsh-plugins\<repo>.
import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const parent = dirname(root)
const owner = 'Octo-o-o-o'

const specs = [
  {
    pkg: 'research',
    repo: 'chatgpt-pro-research',
    description: 'DSH plugin: unattended multi-round research through a real ChatGPT Pro web session.',
  },
  {
    pkg: 'design',
    repo: 'gpt-image-design',
    description: 'DSH plugin: images and HTML demos via a real ChatGPT Pro web session or an OpenAI-compatible image API.',
  },
]

function assert(condition, message) {
  if (!condition) throw new Error(message)
}

for (const spec of specs) {
  const pkgDir = join(root, 'packages', spec.pkg)
  const dest = join(parent, spec.repo)
  assert(existsSync(join(pkgDir, 'lib', 'index.js')), `missing ${spec.pkg}/lib/index.js — run npm run build first`)
  assert(existsSync(join(pkgDir, 'lib', 'client.js')), `missing ${spec.pkg}/lib/client.js — run npm run build first`)

  await mkdir(dest, { recursive: true })
  // Keep .git; replace generated content only.
  for (const name of ['lib', 'resources', 'locale', 'icon.svg', 'cordis.patch.yml', 'README.md', 'LICENSE', 'package.json', 'SYNC.md', '.gitignore']) {
    await rm(join(dest, name), { recursive: true, force: true })
  }

  await cp(join(pkgDir, 'lib'), join(dest, 'lib'), { recursive: true })
  await cp(join(pkgDir, 'resources'), join(dest, 'resources'), { recursive: true })
  await cp(join(pkgDir, 'locale'), join(dest, 'locale'), { recursive: true })
  await cp(join(pkgDir, 'icon.svg'), join(dest, 'icon.svg'))
  await cp(join(pkgDir, 'cordis.patch.yml'), join(dest, 'cordis.patch.yml'))
  await cp(join(pkgDir, 'README.md'), join(dest, 'README.md'))
  await cp(join(root, 'LICENSE'), join(dest, 'LICENSE'))

  const manifest = JSON.parse(await readFile(join(pkgDir, 'package.json'), 'utf8'))
  delete manifest.scripts
  manifest.private = false
  manifest.repository = { type: 'git', url: `git+https://github.com/${owner}/${spec.repo}.git` }
  manifest.homepage = `https://github.com/${owner}/${spec.repo}#readme`
  manifest.bugs = { url: `https://github.com/${owner}/${spec.repo}/issues` }
  await writeFile(join(dest, 'package.json'), `${JSON.stringify(manifest, null, 2)}\n`)

  await writeFile(join(dest, 'SYNC.md'), `# Generated repository

This repository is the public distribution of \`${manifest.name}\` (\`${manifest.version}\`).

- Source of truth: [${owner}/dsh-pro/tree/main/packages/${spec.pkg}](https://github.com/${owner}/dsh-pro/tree/main/packages/${spec.pkg})
- Generated by: \`node scripts/sync-dist.mjs\` in the monorepo
- Do not edit \`lib/\`, \`resources/\`, \`locale/\`, \`icon.svg\`, \`README.md\` or \`LICENSE\` here; change the monorepo and re-run the sync.

The committed \`lib/\` files are what dsh.pub and \`github:\` installs load.
`)

  await writeFile(join(dest, '.gitignore'), `node_modules/\n.DS_Store\n`)

  console.log(`generated ${dest}`)
  console.log(`  ${manifest.name}@${manifest.version} — ${spec.description}`)
}
